#!/usr/bin/env bash
# Gate before full 256px: verify 64->128 trend + optional 256 probe.
# Exit 0 = proceed; exit 1 = not scalable (fixes may have been attempted).
set -uo pipefail
cd "$(dirname "$0")"

LOG=cycles.log
GATE_LOG=scale_gate.log
VERDICT=runs/scale_verdict.json

echo "########## SCALE GATE START $(date +%H:%M:%S)" | tee -a "$GATE_LOG" >> "$LOG"

# Phase A: require completed 128px fair queue; analyze 64->128
if ! python3 exps/scale_verify.py --log "$LOG" --out "$VERDICT" --require_128_fair \
    2>&1 | tee -a "$GATE_LOG"; then
  echo "[gate] 128px fair analysis FAILED — see strategies" | tee -a "$GATE_LOG"
  bash ./run_scale_fixes.sh 2>&1 | tee -a "$GATE_LOG" || true
  if ! python3 exps/scale_verify.py --log "$LOG" --out runs/scale_verdict_recheck.json \
      --require_128_fair 2>&1 | tee -a "$GATE_LOG"; then
    echo "########## SCALE GATE BLOCKED $(date +%H:%M:%S)" | tee -a "$GATE_LOG" >> "$LOG"
    echo "SCALE_VERDICT scalable=FAIL blocked_full_plan=1" >> "$LOG"
    exit 1
  fi
fi

# Phase B: cheap 256px probe before 12k x 1000 full runs
if ! python3 exps/scale_verify.py --log "$LOG" --out runs/scale_verdict_probe.json \
    --probe256 --probe_steps 4000 --probe_base_ch 32 --probe_batch 4 --probe_eval_batch 4 \
    --skip_trend 2>&1 | tee -a "$GATE_LOG"; then
  echo "[gate] 256px probe (base_ch=32) FAILED — trying wider model" | tee -a "$GATE_LOG"
  if ! python3 exps/scale_verify.py --log "$LOG" --out runs/scale_verdict_probe48.json \
      --probe256 --probe_steps 4000 --probe_base_ch 48 --probe_batch 4 --probe_eval_batch 4 \
      --skip_trend 2>&1 | tee -a "$GATE_LOG"; then
    echo "########## SCALE GATE BLOCKED $(date +%H:%M:%S)" | tee -a "$GATE_LOG" >> "$LOG"
    echo "SCALE_VERDICT scalable=FAIL blocked_full_plan=1 probe256=fail" >> "$LOG"
    exit 1
  fi
  export SCALE_FULL_BASE_CH=48
  export SCALE_FULL_BATCH=4
  export SCALE_FULL_EVAL_BATCH=4
  export SCALE_FULL_STEPS=16000
else
  export SCALE_FULL_BASE_CH=32
  export SCALE_FULL_BATCH=4
  export SCALE_FULL_EVAL_BATCH=4
  export SCALE_FULL_STEPS=12000
fi

cat > runs/scale_gate_env.sh <<EOF
# Generated by run_scale_gate.sh — source before full 256px runs
export SCALE_FULL_BASE_CH=${SCALE_FULL_BASE_CH}
export SCALE_FULL_BATCH=${SCALE_FULL_BATCH}
export SCALE_FULL_EVAL_BATCH=${SCALE_FULL_EVAL_BATCH:-4}
export SCALE_FULL_STEPS=${SCALE_FULL_STEPS}
EOF

echo "########## SCALE GATE PASS $(date +%H:%M:%S) base_ch=${SCALE_FULL_BASE_CH} steps=${SCALE_FULL_STEPS}" \
  | tee -a "$GATE_LOG" >> "$LOG"
echo "SCALE_VERDICT scalable=PASS base_ch=${SCALE_FULL_BASE_CH} steps=${SCALE_FULL_STEPS}" >> "$LOG"
exit 0
